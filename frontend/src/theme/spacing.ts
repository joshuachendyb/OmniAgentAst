// 编辑历史: 2026-11-13 商量 - 新建: 全站**间距与行高**唯一真源(补齐控件刻度之外的空白维度)。
//
//   【为什么必须有这份文件】
//   theme/controlScale.ts 管的是"控件长什么样"(高/圆角/内距/焦点环);
//   但界面还有三个维度无处安放: ①两个元素之间隔多远 ②内容离容器边多远 ③一行文字占多高。
//   此前这三处靠"随手写 gap: 6 / marginBottom: 4 / padding: '1px 4px'"过活,
//   结果同一个视觉距离被两套机制各算一半(父 gap 8 + 子 marginBottom 4 = 12),
//   改一处另一处不动 —— 这不是设计, 是记账混乱。
//
//   【铁律一: 一个距离只能有一个归属】
//   任意两个相邻元素的距离, **只能由一处负责**, 二选一, 严禁叠加:
//     · gap    —— 兄弟元素之间的距离, 由**父容器**声明
//     · margin —— 只用于"脱离常规流的贴边补偿"(浮层绝对定位/贴右缘), 严禁用于兄弟间距
//   若同时出现 gap 与 margin/marginBottom 表达同一段距离 → 违规。
//
//   【铁律二: padding 是"内容与容器边"的距离, 不是"元素之间的距离"]
//   padding 用于: 控件内边距(输入框/按钮/chip)、列表容器内容区、面板内容区。
//   padding **不**用于制造元素之间的间距(那属于 gap)。
//
//   【铁律三: margin 原则上一律不用】
//   仅两种例外, 且必须写注释说明为什么:
//     ① 绝对定位/浮层需要贴容器边缘(负 margin 抵消 padding)
//     ② 与父容器 gap 无关的独立小节(如弹窗内分组标题与正文)
//
//   【铁律四: 间距只有一条刻度】
//   数值刻度唯一真源仍是 utils/stepStyles.ts 的 Spacing(4/6/8/12/16/20);
//   本文件**不另立数值**, 只给刻度档位起语义名, 并声明各语义档取哪一档。
//   禁止出现刻度外的数字(2 等)除非在 controlScale 的控件内距里已备案。
//
//   【铁律五: 行高只有三档, 且必须显式下发】
//   行高若不显式写, 就会继承 UI 库缺省 —— 那是库的工程折中, 不是本项目标准(见 controlScale 头注)。
//   故所有承载文字的容器必须显式 lineHeight, 取值只能来自 LineHeight 三档。
//
//   【档位语义】
//   STACK  同列堆叠的兄弟元素之间(如: 引用行 ↔ 输入框)
//   INLINE 同行元素之间(如: 按钮 ↔ 图标)
//   SECTION 独立区块之间(如: 输入区 ↔ 上一区块), 视觉上要能看出分段
//   ROW     一行内容与所在行容器的上下留白(行高补足, 非元素间距)
//
// @author 商量
// @date 2026-11-13

import { Spacing } from '@/utils/stepStyles';

/**
 * 间距语义档 —— 数值一律派生自 Spacing 刻度(唯一真源在 utils/stepStyles.ts), 本文件不另立数值。
 *
 *   ROW     = Spacing.XS(4)  : 行内容与所在行容器的上下补足(最小档)
 *   STACK   = Spacing.SM(6)  : 同列堆叠的兄弟元素之间(如 引用行 ↔ 输入框)
 *   INLINE  = Spacing.SM(6)  : 同行相邻元素之间(如 按钮 ↔ 图标), 与同层兄弟同档(纵向6/横向6视觉等重)
 *   SECTION = Spacing.MD(8)  : 同一区块内各分组之间的横向间隔(如 taskinfo 内的左/中/右组内部)
 *   GROUP   = Spacing.LG(12) : 大分组之间(如 taskinfo 三段之间), 需明显分段
 *
 * 用法: 一律取语义名, 不直接引用 Spacing 数字 —— 语义名承载"这里为什么是这个距离"的意图。
 */
export const Gap = {
  STACK: Spacing.SM,
  INLINE: Spacing.SM,
  SECTION: Spacing.MD,
  GROUP: Spacing.LG,
  ROW: Spacing.XS,
} as const;

/**
 * 行高三档(倍数) —— 文字行盒的唯一标准。
 *
 *   DENSE = 1.4  : 密集区(输入框内、浮层条目、按钮行), 追求信息密度
 *   BODY  = 1.5  : 正文阅读区(说明段、面板正文)
 *   LOOSE = 1.5714: 需要额外呼吸的行(标题行独立成行时)
 *
 * 行高必须是这三档之一, 显式下发; 严禁依赖 UI 库缺省行高。
 */
export const LineHeight = {
  DENSE: 1.4,
  BODY: 1.5,
  LOOSE: 1.5714,
} as const;
